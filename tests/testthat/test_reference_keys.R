test_that("mismatch replay treats factor labels as keys regardless of unused levels", {
  tab <- reference_fixture()
  tab$subject <- factor(tab$subject)
  tab$item <- factor(tab$item)
  refs <- reference_maps(tab, floor = .01)
  fix <- reference_fixations()
  fix$subject <- factor(fix$subject, levels = c("unused", "s3", "s2", "s1"))
  fix$item <- factor(fix$item, levels = c("unused", "c", "b", "a"))
  strata <- sample_controls(fix, n = 2)
  assignments <- mismatch_assignments(strata, refs, n = 2)
  result <- mismatch_draws(strata, refs, assignments = assignments)
  expect_true(all(is.finite(result$contrasts$self_item)))
  plain <- strata
  plain$subject <- as.character(strata$subject)
  plain$item <- as.character(strata$item)
  expected <- mismatch_draws(plain, reference_maps(reference_fixture(), floor = .01), n = 2)
  for (nm in refs$refs) expect_equal(result$contrasts[[nm]], expected$contrasts[[nm]])
  expect_null(attr(result$observed, "scaling"))
  expect_null(attr(result$contrasts, "scaling"))
  expect_s3_class(result$scaling, "eyesim_score_scaling")
})
